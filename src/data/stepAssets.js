export function getStepAssets(chapterId, stepNumber) {
  const cId = Number(chapterId);
  const sNum = Number(stepNumber);
  const stepObj = STEP_ASSETS[cId]?.[sNum];

  if (!stepObj) {
    return {
      leftTop: null,
      leftBottom: null,
      rightTop: null,
      rightBottom: null,
      mobile: [],
    };
  }

  return {
    leftTop: stepObj.leftTop || null,
    leftBottom: stepObj.leftBottom || null,
    rightTop: stepObj.rightTop || null,
    rightBottom: stepObj.rightBottom || null,
    mobile: stepObj.mobile || [],
  };
}
